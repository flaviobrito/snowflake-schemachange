USE SCHEMA {{ database }}.AUDIT;

-- Custom DMF: rows whose email does not look like an email address.
CREATE DATA METRIC FUNCTION IF NOT EXISTS INVALID_EMAIL_COUNT(
    arg_t TABLE (arg_email VARCHAR)
)
RETURNS NUMBER
COMMENT = 'Number of non-null values that are not valid email addresses.'
AS
$$
    SELECT COUNT_IF(
        arg_email IS NOT NULL
        AND NOT REGEXP_LIKE(arg_email, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$')
    )
    FROM arg_t
$$;

-- Custom DMF: rows with negative monetary values.
CREATE DATA METRIC FUNCTION IF NOT EXISTS NEGATIVE_VALUE_COUNT(
    arg_t TABLE (arg_value NUMBER)
)
RETURNS NUMBER
COMMENT = 'Number of negative values.'
AS
$$
    SELECT COUNT_IF(arg_value < 0) FROM arg_t
$$;

